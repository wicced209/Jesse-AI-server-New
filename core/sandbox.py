import ast
import io
import sys
import time
import traceback
from contextlib import redirect_stdout, redirect_stderr

from core.logger import log_event

# Modules the sandbox is allowed to import. Everything else is blocked.
ALLOWED_IMPORTS = frozenset({
    "math", "random", "datetime", "json", "re", "collections",
    "itertools", "functools", "operator", "string", "decimal",
    "fractions", "statistics", "hashlib", "hmac", "base64",
    "uuid", "time", "calendar", "textwrap", "unicodedata",
})

# Names that can never appear in executed code.
BLOCKED_NAMES = frozenset({
    "open", "exec", "eval", "compile", "__import__", "input",
    "exit", "quit", "help", "dir", "globals", "locals", "vars",
    "getattr", "setattr", "delattr", "hasattr", "memoryview",
    "breakpoint",
})

# Attribute access that is always denied.
BLOCKED_ATTRS = frozenset({
    "__class__", "__bases__", "__subclasses__", "__dict__",
    "__globals__", "__code__", "__closure__", "gi_frame",
    "__mro__", "__weakref__",
})

EXEC_TIMEOUT_SECONDS = 30
MAX_OUTPUT_CHARS = 20000


class SandboxViolation(Exception):
    """Raised when generated code attempts a forbidden operation."""


class _ImportGuard(ast.NodeTransformer):
    """Rewrites imports: only allowlisted modules survive."""

    def visit_Import(self, node):
        for alias in node.names:
            root = alias.name.split(".")[0]
            if root not in ALLOWED_IMPORTS:
                raise SandboxViolation(f"import blocked: {alias.name}")
        return node

    def visit_ImportFrom(self, node):
        root = (node.module or "").split(".")[0]
        if root not in ALLOWED_IMPORTS:
            raise SandboxViolation(f"from-import blocked: {node.module}")
        return node


class _SafetyCheck(ast.NodeVisitor):
    """Static scan for dangerous constructs before execution."""

    def visit_Name(self, node):
        if node.id in BLOCKED_NAMES:
            raise SandboxViolation(f"blocked name used: {node.id}")
        self.generic_visit(node)

    def visit_Attribute(self, node):
        if node.attr in BLOCKED_ATTRS:
            raise SandboxViolation(f"blocked attribute access: {node.attr}")
        self.generic_visit(node)

    def visit_Call(self, node):
        # Block dunder calls like ().__class__() etc. — attribute check
        # above already covers the common cases; this is defense in depth.
        self.generic_visit(node)


def _safe_builtins():
    """Minimal builtin set for sandbox execution."""
    import builtins
    safe_names = [
        "abs", "all", "any", "ascii", "bin", "bool", "bytearray", "bytes",
        "chr", "complex", "dict", "divmod", "enumerate", "filter", "float",
        "format", "frozenset", "hex", "int", "isinstance", "issubclass",
        "iter", "len", "list", "map", "max", "min", "next", "oct",
        "ord", "pow", "print", "range", "repr", "reversed", "round",
        "set", "slice", "sorted", "str", "sum", "tuple", "type", "zip",
        "Exception", "ValueError", "TypeError", "KeyError", "IndexError",
        "AttributeError", "RuntimeError", "StopIteration",
    ]
    safe = {n: getattr(builtins, n) for n in safe_names if hasattr(builtins, n)}

    # Guarded __import__: the AST gate already rejected non-allowlisted
    # imports at parse time; this is defense in depth for dynamic imports.
    real_import = builtins.__import__
    def _guarded_import(name, *args, **kwargs):
        root = name.split(".")[0]
        if root not in ALLOWED_IMPORTS:
            raise SandboxViolation(f"import blocked: {name}")
        return real_import(name, *args, **kwargs)
    safe["__import__"] = _guarded_import
    return safe


def execute(code: str, timeout: int = EXEC_TIMEOUT_SECONDS) -> dict:
    """
    Execute Python code inside the sovereign sandbox.

    Returns a dict with: status, stdout, stderr, result, elapsed_ms.
    status is one of: ok | violation | error | timeout.
    """
    started = time.time()
    log_event(f"[SANDBOX] Executing {len(code)} chars of generated code")

    # 1. Static safety scan
    try:
        tree = ast.parse(code)
        _SafetyCheck().visit(tree)
        tree = _ImportGuard().visit(tree)
        ast.fix_missing_locations(tree)
        compiled = compile(tree, "<sovereign_sandbox>", "exec")
    except SandboxViolation as v:
        log_event(f"[SANDBOX] Violation blocked: {v}", "warning")
        return {
            "status": "violation",
            "stdout": "",
            "stderr": f"SandboxViolation: {v}",
            "result": None,
            "elapsed_ms": int((time.time() - started) * 1000),
        }
    except SyntaxError as e:
        return {
            "status": "error",
            "stdout": "",
            "stderr": f"SyntaxError: {e}",
            "result": None,
            "elapsed_ms": int((time.time() - started) * 1000),
        }

    # 2. Execute with restricted globals
    sandbox_globals = {
        "__builtins__": _safe_builtins(),
        "__name__": "__sandbox__",
    }
    stdout_buf = io.StringIO()
    stderr_buf = io.StringIO()
    result_value = None

    try:
        with redirect_stdout(stdout_buf), redirect_stderr(stderr_buf):
            # Timeout is enforced by the caller wrapping this in a
            # thread; here we run directly (Railway worker model).
            exec(compiled, sandbox_globals)
            result_value = sandbox_globals.get("result", None)
    except Exception:
        tb = traceback.format_exc(limit=5)
        log_event("[SANDBOX] Execution raised an exception", "warning")
        return {
            "status": "error",
            "stdout": stdout_buf.getvalue()[:MAX_OUTPUT_CHARS],
            "stderr": tb[-2000:],
            "result": None,
            "elapsed_ms": int((time.time() - started) * 1000),
        }

    elapsed = int((time.time() - started) * 1000)
    log_event(f"[SANDBOX] Execution OK in {elapsed}ms")
    return {
        "status": "ok",
        "stdout": stdout_buf.getvalue()[:MAX_OUTPUT_CHARS],
        "stderr": stderr_buf.getvalue()[:MAX_OUTPUT_CHARS],
        "result": result_value,
        "elapsed_ms": elapsed,
    }


def extract_code(llm_text: str) -> str:
    """
    Pull the first Python code block out of LLM output.
    Handles ```python ... ``` fences and bare code fallback.
    """
    import re
    fenced = re.findall(r"```(?:python)?\s*\n(.*?)```", llm_text, re.DOTALL)
    if fenced:
        # Prefer the longest block (most likely the real implementation).
        return max(fenced, key=len).strip()
    # Fallback: treat the whole response as code if it parses.
    candidate = llm_text.strip()
    try:
        ast.parse(candidate)
        return candidate
    except SyntaxError:
        return ""
